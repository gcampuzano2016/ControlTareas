-- 1. Perfil nuevo H0830_1700
MERGE dbo.R_HorarioLaboral AS D
USING (SELECT 'H0830_1700' AS Codigo, 'Jornada 08:30 a 17:00' AS Nombre, CAST(0 AS BIT) AS EsPredeterminado) AS O
ON D.Codigo = O.Codigo
WHEN MATCHED THEN UPDATE SET D.Nombre=O.Nombre, D.Activo=1
WHEN NOT MATCHED THEN INSERT (Codigo,Nombre,EsPredeterminado,Activo) VALUES (O.Codigo,O.Nombre,O.EsPredeterminado,1);
GO

-- 1.1 Detalle por dia del nuevo perfil (L-V 08:30-17:00, S/D no laborable)
DECLARE @Dias TABLE (DiaSemana TINYINT, NombreDia VARCHAR(15), EsLaborable BIT);
INSERT INTO @Dias VALUES (1,'LUNES',1),(2,'MARTES',1),(3,'MIERCOLES',1),(4,'JUEVES',1),(5,'VIERNES',1),(6,'SABADO',0),(7,'DOMINGO',0);
MERGE dbo.R_HorarioLaboralDetalle AS D
USING (
  SELECT H.IdHorarioLaboral, Dia.DiaSemana, Dia.NombreDia, Dia.EsLaborable,
    CASE WHEN Dia.EsLaborable=1 THEN CAST('08:30:00' AS TIME(0)) ELSE NULL END AS HoraInicio,
    CASE WHEN Dia.EsLaborable=1 THEN CAST('17:00:00' AS TIME(0)) ELSE NULL END AS HoraFin
  FROM @Dias Dia CROSS JOIN dbo.R_HorarioLaboral H WHERE H.Codigo='H0830_1700'
) AS O ON D.IdHorarioLaboral=O.IdHorarioLaboral AND D.DiaSemana=O.DiaSemana
WHEN MATCHED THEN UPDATE SET D.NombreDia=O.NombreDia,D.EsLaborable=O.EsLaborable,D.HoraInicio=O.HoraInicio,D.HoraFin=O.HoraFin,D.Activo=1
WHEN NOT MATCHED THEN INSERT (IdHorarioLaboral,DiaSemana,NombreDia,EsLaborable,HoraInicio,HoraFin,Activo) VALUES (O.IdHorarioLaboral,O.DiaSemana,O.NombreDia,O.EsLaborable,O.HoraInicio,O.HoraFin,1);
GO

