-- 3. Asignacion por cedula (solo activos, sin duplicar)
INSERT INTO dbo.R_UsuarioHorarioLaboral (Id_Responsable,IdHorarioLaboral,FechaDesde,UsuarioRegistro)
SELECT U.Cod_Usuario, H.IdHorarioLaboral, '19000101', 'CARGA_EXCEL'
FROM dbo.R_Usuarios U
INNER JOIN dbo.R_UsuarioHorarioLaboralCargaExcel X ON LTRIM(RTRIM(X.Cedula))=LTRIM(RTRIM(U.Cedula))
INNER JOIN dbo.R_HorarioLaboral H ON H.Codigo = CASE LTRIM(RTRIM(X.HorarioTexto))
    WHEN '8:30 a 17:30' THEN 'H0830_1730'
    WHEN '8:00 a 17:00' THEN 'H0800_1700'
    WHEN '8:30 a 12:30' THEN 'H0830_1230'
    WHEN '8:00 a 16:30' THEN 'H0800_1630'
    WHEN '8:30 a 17:00' THEN 'H0830_1700'
  END
WHERE U.Usuario_Estado='A'
  AND NOT EXISTS (SELECT 1 FROM dbo.R_UsuarioHorarioLaboral A WHERE A.Id_Responsable=U.Cod_Usuario AND A.Activo=1 AND A.FechaHasta IS NULL);
GO